import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { JSDOM } from 'jsdom';
import { createServer } from '../server/ai-server.mjs';
const read = name => readFileSync(new URL('../' + name, import.meta.url), 'utf8');
const { generate, goName, init, HANDOFF_KEY } = await import('data:text/javascript;base64,' + Buffer.from(read('assets/json-to-go.js')).toString('base64'));
test('exported names and primitive mappings', () => {
  assert.equal(goName('user_id'), 'UserID'); assert.equal(goName('userId'), 'UserID');
  const result = generate('{"user_id":1,"price":1.5,"active":true,"name":"John"}');
  for (const fragment of ['UserID int64 `json:"user_id"`', 'Price float64', 'Active bool', 'Name string']) assert.ok(result.includes(fragment), fragment);
});
test('nested structs, nested slices, empty objects and root arrays', () => {
  const result = generate('[{"user":{"name":"A"},"items":[[1,2]],"empty":{}}]');
  for (const fragment of ['type AutoGenerated []AutoGeneratedItem', 'type AutoGeneratedItemUser struct', 'Items [][]int64', 'struct {}']) assert.ok(result.includes(fragment), fragment);
  assert.match(generate('[]'), /type AutoGenerated \[\]interface\{\}/);
});
test('array-wide inference merges fields, numbers and nulls', () => {
  const result = generate('[{"id":1,"value":null,"list":[]},{"id":2.5,"value":"x","extra":true,"list":[1]}]');
  assert.match(result, /ID float64/); assert.match(result, /Value \*string/);
  assert.match(result, /Extra \*bool/); assert.match(result, /List \[\]int64/);
  assert.match(generate('{"mixed":[1,"x"],"unknown":null}'), /Mixed \[\]interface\{\}/);
});
test('root and field collisions are unique and special keys are safe', () => {
  const result = generate('{"foo_bar":{},"fooBar":{},"123":true,"__proto__":{"id":1}}', { rootName: 'foo bar' });
  assert.match(result, /FooBar FooBarFooBar/); assert.match(result, /FooBar2 FooBarFooBar2/);
  assert.match(result, /Field123 bool/); assert.match(result, /Proto FooBarProto/);
  for (const key of ['', '-', 'a,b', 'a"b', 'a\\b', 'a`b', '😀']) assert.throws(() => generate(JSON.stringify({ [key]: 1 })), /struct tag/);
  assert.doesNotThrow(() => generate('{"a,b":1}', { includeTags: false }));
});
test('tag options, empty input and invalid input', () => {
  assert.match(generate('{"x":1}', { rootName: 'my type', omitEmpty: true }), /type MyType struct[\s\S]*json:"x,omitempty"/);
  assert.doesNotMatch(generate('{"x":1}', { includeTags: false, omitEmpty: true }), /`json:/);
  assert.equal(generate(''), '');
  for (const value of ['{', 'null', '3', 'true', '"text"', '{"x":1e999}', '{"x":9007199254740993}']) assert.throws(() => generate(value));
  assert.throws(() => generate('['.repeat(102) + '0' + ']'.repeat(102)), /depth/);
});
test('generated Go is accepted by gofmt and encoding/json unmarshaling', () => {
  const dir = mkdtempSync(join(tmpdir(), 'joinjson-go-'));
  try {
    const data = [{ user_id: 1, profile: { name: 'A' }, optional: null, scores: [1, 2.5] }, { user_id: 2, profile: {}, optional: 'yes', enabled: true }];
    const generated = generate(JSON.stringify(data));
    const file = join(dir, 'types.go'); writeFileSync(file, generated);
    const format = spawnSync('gofmt', ['-e', file], { encoding: 'utf8' });
    assert.equal(format.status, 0, format.stderr);
    writeFileSync(join(dir, 'main.go'), 'package main\nimport "encoding/json"\nfunc main(){ var value AutoGenerated; if err := json.Unmarshal([]byte(' + JSON.stringify(JSON.stringify(data)) + '), &value); err != nil { panic(err) } }');
    const run = spawnSync('go', ['run', file, join(dir, 'main.go')], { encoding: 'utf8', timeout: 60000 });
    assert.equal(run.status, 0, run.stderr);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
test('UI handles one-time transfer, live input, options, copy, download and clear', async () => {
  const dom = new JSDOM(read('json-to-go.html'), { url: 'https://www.joinjson.com/json-to-go', pretendToBeVisual: true });
  const w = dom.window, d = w.document;
  try {
    let copied, filename, blob;
    w.sessionStorage.setItem(HANDOFF_KEY, '{"user_id":1}');
    Object.defineProperty(w.navigator, 'clipboard', { value: { writeText: async text => { copied = text; } } });
    w.URL.createObjectURL = value => { blob = value; return 'blob:test'; }; w.URL.revokeObjectURL = () => {};
    w.HTMLAnchorElement.prototype.click = function () { filename = this.download; };
    init(d);
    const input = d.getElementById('go-json-input'), output = d.getElementById('go-output');
    assert.equal(w.sessionStorage.getItem(HANDOFF_KEY), null); assert.match(output.value, /UserID int64/);
    d.getElementById('go-copy').click(); await Promise.resolve(); assert.equal(copied, output.value); assert.equal(d.getElementById('go-copy').textContent, 'Copied!');
    d.getElementById('go-download').click(); assert.equal(filename, 'autogenerated.go'); assert.equal(blob.type, 'text/plain;charset=utf-8');
    d.getElementById('go-omitempty').checked = true; d.getElementById('go-omitempty').dispatchEvent(new w.Event('change')); assert.match(output.value, /omitempty/);
    input.value = '{'; input.dispatchEvent(new w.Event('input')); assert.equal(output.value, ''); assert.ok(d.getElementById('go-copy').disabled);
    await new Promise(resolve => setTimeout(resolve, 200)); assert.equal(input.getAttribute('aria-invalid'), 'true'); assert.equal(d.getElementById('go-error').hidden, false);
    input.value = '[true]'; input.dispatchEvent(new w.Event('paste')); await new Promise(resolve => setTimeout(resolve, 200)); assert.match(output.value, /\[\]bool/);
    d.getElementById('root-struct-name').value = 'response'; d.getElementById('root-struct-name').dispatchEvent(new w.Event('change')); assert.match(output.value, /type Response/);
    d.getElementById('go-clear').click(); assert.equal(input.value, ''); assert.equal(output.value, ''); assert.equal(d.getElementById('go-error').hidden, true);
  } finally { w.close(); }
});
test('clean route, trailing slash and HTML serve the standalone tool', async () => {
  assert.equal(read('json-to-go/index.html'), read('json-to-go.html'));
  const server = createServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    for (const route of ['/json-to-go', '/json-to-go/', '/json-to-go.html']) {
      const response = await fetch(`http://127.0.0.1:${server.address().port}${route}`); assert.equal(response.status, 200);
      const dom = new JSDOM(await response.text()), d = dom.window.document;
      assert.equal(d.title, 'JSON to Go Struct Generator Online | JoinJSON');
      assert.ok(d.querySelector('header a[href="/json-to-go"]')); assert.ok(d.querySelector('footer a[href="/json-to-go"]'));
      assert.ok(d.querySelector('#go-json-input')); dom.window.close();
    }
    assert.ok(JSON.parse(read('vercel.json')).rewrites.some(rule => rule.source === '/json-to-go' && rule.destination === '/json-to-go.html'));
    assert.match(read('sitemap.xml'), /https:\/\/www.joinjson.com\/json-to-go/);
  } finally { await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); }
});
