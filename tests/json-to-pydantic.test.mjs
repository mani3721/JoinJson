import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { JSDOM } from 'jsdom';
import { createServer } from '../server/ai-server.mjs';
const read = name => readFileSync(new URL('../' + name, import.meta.url), 'utf8');
const { generate, init, HANDOFF_KEY } = await import('data:text/javascript;base64,' + Buffer.from(read('assets/json-to-pydantic.js')).toString('base64'));
const pause = () => new Promise(resolve => setTimeout(resolve, 200));
test('primitive mappings and dependency-ordered child classes', () => {
  const result = generate('{"id":1,"price":1.5,"enabled":true,"name":"John","profile":{"city":"X"},"tags":["a"]}');
  for (const fragment of ['id: int', 'price: float', 'enabled: bool', 'name: str', 'tags: List[str]', 'profile: AutoGeneratedProfile']) assert.ok(result.includes(fragment), fragment);
  assert.ok(result.indexOf('class AutoGeneratedProfile') < result.indexOf('class AutoGenerated(BaseModel)'));
});
test('arrays merge all object shapes, promote numbers and handle nulls and empty lists', () => {
  const result = generate('[{"id":1,"name":null,"list":[]},{"id":2.5,"name":"A","active":true,"list":[1]}]');
  for (const fragment of ['RootModel[List[AutoGeneratedItem]]', 'id: float', 'name: Optional[str] = None', 'active: Optional[bool] = None', 'list: List[int]']) assert.ok(result.includes(fragment), fragment);
  assert.match(generate('{"mixed":[1,"x",true],"unknown":null}'), /mixed: List\[Union\[int, str, bool\]\]/);
  assert.match(generate('[]'), /RootModel\[List\[Any\]\]/);
});
test('snake_case aliases, keywords, reserved names and collision handling', () => {
  const result = generate('{"userId":1,"user_id":2,"class":"a","model_dump":{},"__proto__":true,"":1,"a\\\"b":2}', { snakeCase: true });
  assert.match(result, /user_id: int = Field\(default=\.\.\., alias="userId"\)/);
  assert.match(result, /user_id2: int/); assert.match(result, /class_: str/); assert.match(result, /field_model_dump/);
  assert.match(result, /field_proto/); assert.match(result, /alias=""/);
});
test('Field options, optional off, dataclasses and input validation', () => {
  assert.match(generate('{"x":1}', { fieldDefaults: true }), /from pydantic import BaseModel, Field/);
  assert.match(generate('{"x":1}', { fieldDefaults: true }), /x: int = Field\(default=\.\.\.\)/);
  assert.doesNotMatch(generate('[{"x":1},{}]', { optional: false }), /Optional|= None/);
  const result = generate('[{"camelCase":null},{"camelCase":"x","id":1}]', { framework: 'dataclass', snakeCase: true });
  assert.match(result, /from dataclasses import dataclass, field/);
  assert.match(result, /@dataclass\(kw_only=True\)/); assert.match(result, /metadata=\{"json_key": "camelCase"\}/);
  assert.doesNotMatch(result, /pydantic/);
  assert.equal(generate(''), '');
  for (const source of ['{', 'null', '1', 'true', '"x"', '{"n":1e999}', '{"n":9007199254740993}']) assert.throws(() => generate(source));
  assert.throws(() => generate('['.repeat(102) + '0' + ']'.repeat(102)), /depth/);
});
test('generated dataclasses execute and generated Pydantic code compiles as Python', () => {
  const sources = ['{"userId":1,"profile":{"city":"X"},"unknown":null}', '[{"class":1},{"id":2}]', '[]', '{"List":{"a":1},"list":{"b":2},"\\u2028":true}', '{"mixed":[{},1,"x",null,{"a":2}]}'];
  for (const source of sources) for (const framework of ['dataclass', 'pydantic']) {
    const code = generate(source, { framework, snakeCase: true, fieldDefaults: true });
    const script = framework === 'dataclass' ? 'import sys\nexec(compile(sys.stdin.read(), "models.py", "exec"))' : 'import sys\ncompile(sys.stdin.read(), "models.py", "exec")';
    const result = spawnSync('python3', ['-c', script], { input: code, encoding: 'utf8' });
    assert.equal(result.status, 0, result.stderr + '\n' + code);
  }
});
test('generated models validate with Pydantic v2', { skip: !process.env.PYDANTIC_PYTHON }, () => {
  const samples = [{ userId: 1, profile: { city: 'X' }, unknown: null }, [{ id: 1 }, { name: 'Ana' }], [], { str: 'x', List: [1], schema_json: 'x', model_dump: 1, '😀': 2 }, { items: [{ x: 1 }, 'text', true, { y: 2 }] }];
  for (const value of samples) for (const optional of [true, false]) {
    const code = generate(JSON.stringify(value), { snakeCase: true, fieldDefaults: true, optional });
    const script = code + '\nAutoGenerated.model_rebuild()\n' + (optional ? 'AutoGenerated.model_validate_json(' + JSON.stringify(JSON.stringify(value)) + ')\n' : '');
    const result = spawnSync(process.env.PYDANTIC_PYTHON, ['-c', script], { encoding: 'utf8' });
    assert.equal(result.status, 0, result.stderr + '\n' + code);
  }
});
test('UI transfer, events, controls, copy, download, errors and clear', async () => {
  const dom = new JSDOM(read('json-to-pydantic.html'), { url: 'https://www.joinjson.com/json-to-pydantic', pretendToBeVisual: true });
  const w = dom.window, d = w.document, get = id => d.getElementById('pydantic-' + id);
  try {
    let copied, filename, blob;
    w.sessionStorage.setItem(HANDOFF_KEY, '{"userId":1}');
    Object.defineProperty(w.navigator, 'clipboard', { value: { writeText: async text => { copied = text; } } });
    w.URL.createObjectURL = value => { blob = value; return 'blob:test'; }; w.URL.revokeObjectURL = () => {};
    w.HTMLAnchorElement.prototype.click = function () { filename = this.download; };
    init(d); assert.equal(w.sessionStorage.getItem(HANDOFF_KEY), null); assert.match(get('output').value, /userId: int/);
    get('copy').click(); await Promise.resolve(); assert.equal(copied, get('output').value); assert.equal(get('copy').textContent, 'Copied!');
    get('download').click(); assert.equal(filename, 'models.py'); assert.equal(blob.type, 'text/x-python;charset=utf-8');
    get('snake').checked = true; get('snake').dispatchEvent(new w.Event('change')); assert.match(get('output').value, /user_id/);
    const radio = d.querySelector('[value="dataclass"]'); radio.checked = true; radio.dispatchEvent(new w.Event('change'));
    assert.match(get('output').value, /@dataclass/); assert.equal(get('defaults').disabled, true);
    const input = get('json-input'); input.value = '{'; input.dispatchEvent(new w.Event('keyup')); assert.equal(get('output').value, '');
    await pause(); assert.equal(input.getAttribute('aria-invalid'), 'true'); assert.equal(get('error').hidden, false); assert.equal(get('copy').disabled, true);
    input.value = '[true]'; input.dispatchEvent(new w.Event('paste')); await pause(); assert.match(get('output').value, /List\[bool\]/);
    get('clear').click(); assert.equal(input.value, ''); assert.equal(get('output').value, ''); assert.equal(get('error').hidden, true);
  } finally { w.close(); }
});
test('standalone clean routes, metadata, shared navigation and sitemap', async () => {
  assert.equal(read('json-to-pydantic/index.html'), read('json-to-pydantic.html'));
  const server = createServer(); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    for (const route of ['/json-to-pydantic', '/json-to-pydantic/', '/json-to-pydantic.html']) {
      const response = await fetch(`http://127.0.0.1:${server.address().port}${route}`); assert.equal(response.status, 200);
      const dom = new JSDOM(await response.text()), d = dom.window.document;
      assert.equal(d.title, 'JSON to Pydantic Model & Python Dataclass Generator | JoinJSON');
      assert.ok(d.querySelector('header a[href="/json-to-pydantic"]')); assert.ok(d.querySelector('footer a[href="/json-to-pydantic"]'));
      assert.ok(d.querySelector('#pydantic-json-input')); dom.window.close();
    }
    assert.ok(JSON.parse(read('vercel.json')).rewrites.some(rule => rule.source === '/json-to-pydantic' && rule.destination === '/json-to-pydantic.html'));
    assert.match(read('sitemap.xml'), /https:\/\/www.joinjson.com\/json-to-pydantic/);
  } finally { await new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }); }
});
