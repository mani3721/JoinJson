import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
test('TypeScript uses shared CodeMirror input, read-only output, lazy switching and private clear', async t => {
  const dom = new JSDOM(read('index.html'), { url: 'https://www.joinjson.com/', runScripts: 'outside-only', pretendToBeVisual: true });
  const win = dom.window;
  for (const name of ['window', 'document', 'navigator', 'MutationObserver', 'HTMLTextAreaElement', 'CustomEvent', 'Event', 'HTMLElement', 'Node', 'Window', 'getComputedStyle']) Object.defineProperty(globalThis, name, { value: name === 'getComputedStyle' ? win.getComputedStyle.bind(win) : name === 'window' ? win : win[name], configurable: true });
  globalThis.requestAnimationFrame = win.requestAnimationFrame.bind(win); globalThis.cancelAnimationFrame = win.cancelAnimationFrame.bind(win);
  win.Range.prototype.getClientRects = () => [];
  win.Range.prototype.getBoundingClientRect = () => ({ left: 0, right: 0, top: 0, bottom: 0, width: 0, height: 0 });
  for (const file of ['json-error-helper.js', 'editor-find.js', 'json-to-zod.js', 'json-to-zod-ui.js', 'json-to-typescript.js', 'json-to-typescript-ui.js']) win.eval(read('assets/' + file));
  const { enhance } = await import('../src/editors.mjs');
  enhance(); assert.equal(win.JMEditors.get('typescript-input'), undefined);
  win.document.querySelector('#tool-menu [data-tool="json-to-typescript"]').click(); enhance();
  const input = win.JMEditors.get('typescript-input'), output = win.JMEditors.get('typescript-output');
  assert.ok(input); assert.ok(output);
  t.after(() => {
    for (const id of ['typescript-input', 'typescript-output', 'zod-input', 'zod-output']) win.JMEditors.get(id)?.destroy();
    dom.window.close();
  });
  win.document.getElementById('typescript-example').click();
  assert.match(output.text(), /export interface Root/);
  assert.equal(output.view.contentDOM.getAttribute('contenteditable'), 'false');
  assert.equal(output.view.dom.parentElement.previousElementSibling.textContent.includes('Format JSON'), false);
  input.view.dispatch({ changes: { from: 0, to: input.view.state.doc.length, insert: '[true,null]' } });
  assert.equal(win.document.getElementById('typescript-input').value, '[true,null]');
  await new Promise(resolve => setTimeout(resolve, 350));
  assert.match(output.text(), /Array<boolean \| null>/);
  assert.equal(output.view.dom.querySelector('.cm-lintRange-error'), null);
  win.document.getElementById('typescript-zod').click(); enhance();
  assert.match(win.JMEditors.get('zod-output').text(), /z\.array\(z\.boolean\(\)\.nullable\(\)\)/);
  win.document.querySelector('[data-tool="json-to-typescript"]').click();
  win.document.getElementById('typescript-clear').click();
  assert.equal(input.text(), ''); assert.equal(output.text(), '');
  const { undo } = await import('@codemirror/commands');
  assert.equal(undo(input.view), false); assert.equal(undo(output.view), false);
});
