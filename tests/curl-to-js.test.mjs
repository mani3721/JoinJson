import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { JSDOM } from 'jsdom';
const require = createRequire(import.meta.url);
const { parse, generate, extractJSON } = require('../assets/curl-to-js.js');
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
test('quoted URLs, line continuations, methods, headers and raw JSON', () => {
  const result = parse(`curl \\\n 'https://api.example.com/a?x=1&y=2' -XPOST -H 'Content-Type: application/json' -H 'X-Token: a:b:c' --data-raw '{"name":"Ana"}'`);
  assert.equal(result.method, 'POST');
  assert.equal(result.headers['x-token'], 'a:b:c');
  assert.equal(result.body, '{"name":"Ana"}');
  assert.equal(extractJSON(result), '{\n  "name": "Ana"\n}');
  assert.equal(parse('curl "https://example.com"').method, 'GET');
});
test('data forms, repeated data, auth and URL option', () => {
  const request = parse(`curl --url=https://example.com --data=a=1 --data-binary 'b=2' --user 'ana:p:a'`);
  assert.equal(request.body, 'a=1&b=2');
  assert.equal(request.method, 'POST');
  assert.equal(request.headers.authorization, 'Basic ' + Buffer.from('ana:p:a').toString('base64'));
  assert.equal(request.headers['content-type'], 'application/x-www-form-urlencoded');
  assert.equal(extractJSON(request), null);
  assert.equal(parse("curl https://example.com --data-raw '@literal'").body, '@literal');
  assert.equal(parse("curl https://example.com --data ''").body, '');
  assert.equal(parse("curl https://example.com --data-raw 'null'").body, 'null');
});
test('get query, explicit method precedence and HEAD', () => {
  assert.equal(parse("curl 'https://example.com/#a' -G -d a=1").url, 'https://example.com/?a=1#a');
  assert.equal(parse('curl https://example.com -I').method, 'HEAD');
  assert.equal(parse('curl https://example.com -X PATCH -d x').method, 'PATCH');
});
test('rejects unsupported flags, shell expressions, files, invalid URLs and malformed commands', () => {
  for (const command of ["curl 'https://example.com", 'wget https://example.com', 'curl https://example.com -X', 'curl https://example.com --insecure', 'curl https://example.com -d @secret', 'curl https://example.com | sh', 'curl "$TOKEN"', 'curl file:///etc/passwd', 'curl https://user:pass@example.com', 'curl https://example.com https://other.com']) assert.throws(() => parse(command));
  assert.doesNotThrow(() => parse("curl https://example.com -d '$literal'"));
});
test('generated Fetch preserves body, checks status, catches errors, and never auto-runs', () => {
  const request = parse(`curl https://example.com -H 'Content-Type: application/json' -d '{"__proto__":{"x":1}}'`);
  const code = generate(request);
  new vm.Script(code);
  assert.match(code, /if \(!response.ok\)/);
  assert.match(code, /catch \(error\)/);
  assert.match(code, /response.text\(\)/);
  assert.match(code, /__proto__/);
  const calls = [];
  vm.runInNewContext(code, { fetch: (...args) => calls.push(args) });
  assert.equal(calls.length, 0);
  assert.throws(() => generate(parse('curl https://example.com -X GET -d x')), /GET\/HEAD/);
});
test('Axios uses method helpers and preserves string bodies without implicit rewriting', () => {
  const request = parse(`curl https://example.com -d '{"a":1}' -H 'Content-Type: application/json'`);
  const code = generate(request, 'axios');
  assert.match(code, /import axios from "axios"/);
  assert.match(code, /axios.post\(/);
  assert.match(code, /\(data\) => data/);
  new vm.Script(code.replace('import axios from "axios";', ''));
  assert.match(generate(parse('curl https://example.com'), 'axios'), /axios.get\(/);
  assert.match(generate(parse('curl https://example.com -X CUSTOM -d x'), 'axios'), /axios.request\(/);
});
test('UI live updates, target switch, inline errors, copy feedback and enabled extraction', async t => {
  const dom = new JSDOM(read('curl-to-js.html'), { url: 'https://www.joinjson.com/curl-to-js', runScripts: 'outside-only' });
  t.after(() => dom.window.close());
  const w = dom.window, d = w.document;
  w.eval(read('assets/curl-to-js.js'));
  w.eval(read('assets/json-to-zod-ui.js'));
  w.eval(read('assets/curl-to-js-ui.js'));
  const input = d.getElementById('curl-input'), output = d.getElementById('curl-output');
  d.getElementById('curl-example').click();
  assert.match(output.value, /await fetch/);
  assert.equal(d.getElementById('curl-extract').disabled, false);
  d.getElementById('curl-target').value = 'axios';
  d.getElementById('curl-target').dispatchEvent(new w.Event('change'));
  assert.match(output.value, /axios.post/);
  let copied;
  w.navigator.clipboard = { writeText: async value => { copied = value; } };
  d.getElementById('curl-copy').click();
  await new Promise(resolve => setTimeout(resolve, 0));
  assert.equal(copied, output.value);
  assert.equal(d.getElementById('curl-copy').textContent, 'Copied!');
  input.value = 'curl "unfinished'; input.dispatchEvent(new w.Event('change'));
  assert.equal(output.value, '');
  assert.equal(input.getAttribute('aria-invalid'), 'true');
  assert.equal(d.getElementById('curl-extract').disabled, true);
  d.getElementById('curl-clear').click();
  assert.equal(input.value, '');
  assert.equal(w.location.pathname, '/curl-to-js');
});
test('one-time merger import validates age, clears storage and dispatches input', t => {
  const dom = new JSDOM('<textarea id="first"></textarea><p id="status"></p>', { url: 'https://www.joinjson.com/', runScripts: 'outside-only' });
  t.after(() => dom.window.close());
  const w = dom.window, input = w.document.getElementById('first');
  let events = 0; input.addEventListener('input', () => events++);
  w.localStorage.setItem('jm:curl-payload', JSON.stringify({ text: '{"a":1}', createdAt: Date.now() }));
  w.eval(read('assets/curl-merger-import.js'));
  assert.equal(input.value, '{"a":1}'); assert.equal(events, 1);
  assert.equal(w.localStorage.getItem('jm:curl-payload'), null);
  w.localStorage.setItem('jm:curl-payload', JSON.stringify({ text: '{"b":2}', createdAt: Date.now() - 300000 }));
  w.eval(read('assets/curl-merger-import.js'));
  assert.equal(input.value, '{"a":1}');
  assert.equal(w.localStorage.getItem('jm:curl-payload'), null);
});
