import test from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
const require = createRequire(import.meta.url);
const read = path => readFileSync(new URL('../' + path, import.meta.url), 'utf8');
test('YAML shares lazy editors, skips JSON-only lint/format and clears undo history', async t => {
  const dom = new JSDOM(read('index.html'), { url: 'https://www.joinjson.com/', runScripts: 'outside-only', pretendToBeVisual: true });
  const win = dom.window;
  for (const name of ['window', 'document', 'navigator', 'MutationObserver', 'HTMLTextAreaElement', 'CustomEvent', 'Event', 'HTMLElement', 'Node', 'Window', 'getComputedStyle']) Object.defineProperty(globalThis, name, { value: name === 'getComputedStyle' ? win.getComputedStyle.bind(win) : name === 'window' ? win : win[name], configurable: true });
  globalThis.requestAnimationFrame = win.requestAnimationFrame.bind(win); globalThis.cancelAnimationFrame = win.cancelAnimationFrame.bind(win);
  win.Range.prototype.getClientRects = () => [];
  win.Range.prototype.getBoundingClientRect = () => ({ left: 0, right: 0, top: 0, bottom: 0, width: 0, height: 0 });
  win.jsyaml = require('js-yaml');
  for (const file of ['json-error-helper.js', 'editor-find.js', 'json-to-zod-ui.js', 'json-to-yaml.js', 'json-to-yaml-ui.js']) win.eval(read('assets/' + file));
  const { enhance } = await import('../src/editors.mjs');
  enhance(); assert.equal(win.JMEditors.get('yaml-input'), undefined);
  win.document.querySelector('[data-tool="json-to-yaml"]').click(); enhance();
  const input = win.JMEditors.get('yaml-input'), output = win.JMEditors.get('yaml-output');
  t.after(() => { input?.destroy(); output?.destroy(); dom.window.close(); });
  assert.ok(input); assert.ok(output);
  win.document.getElementById('yaml-example').click(); assert.match(output.text(), /name: Ana/);
  assert.equal(output.view.contentDOM.getAttribute('contenteditable'), 'false');
  for (const editor of [input, output]) assert.equal(editor.view.dom.parentElement.previousElementSibling.textContent.includes('Format JSON'), false);
  win.document.getElementById('yaml-to-json').click();
  input.view.dispatch({ changes: { from: 0, to: input.view.state.doc.length, insert: 'active: true\n' } });
  await new Promise(resolve => setTimeout(resolve, 350));
  assert.equal(JSON.parse(output.text()).active, true);
  assert.equal(input.view.dom.querySelector('.cm-lintRange-error'), null);
  assert.equal(output.view.dom.querySelector('.cm-lintRange-error'), null);
  assert.match(input.view.contentDOM.getAttribute('aria-label'), /Input YAML/);
  win.document.getElementById('yaml-clear').click(); assert.equal(input.text(), ''); assert.equal(output.text(), '');
  const { undo } = await import('@codemirror/commands');
  assert.equal(undo(input.view), false); assert.equal(undo(output.view), false);
});
