/* Local JSON sample inference. No dependencies or network requests. */
export const HANDOFF_KEY = 'joinjson:pydantic-input';
const keywords = new Set(('False None True and as assert async await break class continue def del elif else except finally for from global if import in is lambda nonlocal not or pass raise return try while with yield match case type').split(' '));
const reserved = new Set(['Any', 'List', 'Optional', 'Union', 'BaseModel', 'Field', 'RootModel', 'dataclass', 'field', 'str', 'int', 'float', 'bool', 'AutoGenerated']);
function words(value) {
  return String(value).replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').replace(/([a-z0-9])([A-Z])/g, '$1_$2');
}
function fieldName(key, snake) {
  let name = (snake ? words(key).toLowerCase() : String(key)).replace(/[^a-zA-Z0-9_]/g, '_');
  if (!name || !/[a-zA-Z]/.test(name)) name = 'field_' + name;
  if (/^[0-9_]/.test(name) || name.startsWith('model_')) name = 'field_' + name.replace(/^_+/, '');
  if (keywords.has(name) || reserved.has(name) || ['schema', 'schema_json', 'json', 'dict', 'copy', 'validate', 'construct', 'parse_obj', 'parse_raw', 'parse_file', 'from_orm', 'update_forward_refs', 'Config'].includes(name)) name += '_';
  return name;
}
function className(value) {
  let name = words(value).split(/[^a-zA-Z0-9]+/).filter(Boolean).map(word => word[0].toUpperCase() + word.slice(1)).join('') || 'Item';
  if (/^[0-9]/.test(name)) name = 'Model' + name;
  return name;
}
function allocate(name, used) {
  const base = name; let suffix = 2;
  while (used.has(name)) name = base + suffix++;
  used.add(name); return name;
}
// JSON string escaping is valid Python string escaping after escaping non-ASCII.
const literal = value => JSON.stringify(value).replace(/[\u007f-\u{10ffff}]/gu, char => {
  const code = char.codePointAt(0);
  return code > 0xffff ? '\\U' + code.toString(16).padStart(8, '0') : '\\u' + code.toString(16).padStart(4, '0');
});
function infer(value, depth = 0) {
  if (depth > 100) throw new Error('JSON nesting exceeds the supported depth of 100 levels.');
  if (value === null) return { kind: 'null' };
  if (Array.isArray(value)) return { kind: 'array', item: value.reduce((a, b) => merge(a, infer(b, depth + 1)), undefined) };
  if (typeof value === 'object') return { kind: 'object', fields: new Map(Object.entries(value).map(([key, child]) => [key, { schema: infer(child, depth + 1) }])) };
  if (typeof value === 'number') {
    if (!Number.isFinite(value) || (Number.isInteger(value) && !Number.isSafeInteger(value))) throw new Error('A number is outside JavaScript’s safe range. Encode exact large integers as strings before generating models.');
    return { kind: Number.isInteger(value) ? 'int' : 'float' };
  }
  return { kind: typeof value === 'boolean' ? 'bool' : 'str' };
}
function merge(a, b) {
  if (!a) return b;
  if (!b) return a;
  if (a.kind === 'null') return b.kind === 'null' ? a : { ...b, nullable: true };
  if (b.kind === 'null') return { ...a, nullable: true };
  const nullable = a.nullable || b.nullable;
  if (a.kind !== b.kind) {
    if (['int', 'float'].includes(a.kind) && ['int', 'float'].includes(b.kind)) return { kind: 'float', nullable };
    const variants = [...(a.kind === 'union' ? a.variants : [a]), ...(b.kind === 'union' ? b.variants : [b])];
    const grouped = new Map();
    for (const schema of variants) grouped.set(schema.kind, merge(grouped.get(schema.kind), schema));
    return { kind: 'union', variants: [...grouped.values()], nullable };
  }
  if (a.kind === 'object') {
    const fields = new Map();
    for (const key of new Set([...a.fields.keys(), ...b.fields.keys()])) {
      const left = a.fields.get(key), right = b.fields.get(key);
      fields.set(key, { schema: merge(left?.schema, right?.schema), optional: !left || !right || left.optional || right.optional });
    }
    return { kind: 'object', fields, nullable };
  }
  if (a.kind === 'array') return { kind: 'array', item: merge(a.item, b.item), nullable };
  if (a.kind === 'union') {
    const grouped = new Map();
    for (const schema of [...a.variants, ...b.variants]) grouped.set(schema.kind, merge(grouped.get(schema.kind), schema));
    return { kind: 'union', variants: [...grouped.values()], nullable };
  }
  return { ...a, nullable };
}
export function generate(source, { framework = 'pydantic', optional = true, fieldDefaults = false, snakeCase = false } = {}) {
  if (!source.trim()) return '';
  if (!['pydantic', 'dataclass'].includes(framework)) throw new Error('Unknown target framework.');
  const value = JSON.parse(source);
  if (!value || typeof value !== 'object') throw new Error('Paste a JSON object or array, not a primitive value.');
  const schema = infer(value), definitions = [], typing = new Set(), used = new Set(reserved);
  let needsField = false, needsDataclassField = false;
  const isPydantic = framework === 'pydantic';
  function typed(name) { typing.add(name); return name; }
  function render(node, hint, missing = false) {
    let type;
    if (!node || node.kind === 'null') type = typed('Any');
    else if (node.kind === 'object') {
      type = allocate(className(hint), used); object(node, type);
    } else if (node.kind === 'array') type = typed('List') + '[' + render(node.item, hint + 'Item') + ']';
    else if (node.kind === 'union') type = typed('Union') + '[' + [...new Set(node.variants.map((child, index) => render(child, hint + (index ? index + 1 : ''))))].join(', ') + ']';
    else type = node.kind;
    if (optional && (missing || node?.nullable) && type !== 'Any') type = typed('Optional') + '[' + type + ']';
    return type;
  }
  function object(node, name) {
    const names = new Set();
    const lines = [...node.fields].map(([key, entry]) => {
      const field = allocate(fieldName(key, snakeCase), names);
      const type = render(entry.schema, name + className(field), entry.optional);
      const canDefault = optional && (entry.optional || entry.schema.nullable || entry.schema.kind === 'null');
      let suffix = canDefault ? ' = None' : '';
      if (isPydantic && (fieldDefaults || field !== key)) {
        needsField = true;
        suffix = ' = Field(default=' + (canDefault ? 'None' : '...') + (field !== key ? ', alias=' + literal(key) : '') + ')';
      } else if (!isPydantic && field !== key) {
        needsDataclassField = true;
        suffix = ' = field(' + (canDefault ? 'default=None, ' : '') + 'metadata={"json_key": ' + literal(key) + '})';
      }
      return '    ' + field + ': ' + type + suffix;
    });
    definitions.push((isPydantic ? '' : '@dataclass(kw_only=True)\n') + 'class ' + name + (isPydantic ? '(BaseModel)' : '') + ':\n' + (lines.length ? lines.join('\n') : '    pass'));
  }
  if (schema.kind === 'object') object(schema, 'AutoGenerated');
  else {
    const root = render(schema, 'AutoGenerated');
    if (isPydantic) definitions.push('class AutoGenerated(RootModel[' + root + ']):\n    pass');
    else definitions.push('AutoGenerated = ' + root);
  }
  const imports = [];
  if (isPydantic) imports.push('from pydantic import ' + ['BaseModel', ...(needsField ? ['Field'] : []), ...(schema.kind === 'array' ? ['RootModel'] : [])].join(', '));
  else imports.push('from dataclasses import dataclass' + (needsDataclassField ? ', field' : ''));
  if (typing.size) imports.push('from typing import ' + [...typing].sort().join(', '));
  return '# Generated from a JSON sample. Review types against your API schema.\n# Requires Python 3.10+' + (isPydantic ? ' and Pydantic v2.' : '. Dataclasses do not validate or deserialize JSON automatically.') + '\n\n' + imports.join('\n') + '\n\n\n' + definitions.join('\n\n\n') + '\n';
}
export function init(doc = document) {
  const input = doc.getElementById('pydantic-json-input');
  if (!input) return;
  const win = doc.defaultView, output = doc.getElementById('pydantic-output');
  const error = doc.getElementById('pydantic-error'), status = doc.getElementById('pydantic-status');
  const copy = doc.getElementById('pydantic-copy'), download = doc.getElementById('pydantic-download');
  const defaults = doc.getElementById('pydantic-defaults');
  let timer, feedback, revision = 0;
  function invalidate() {
    revision++; win.clearTimeout(timer); win.clearTimeout(feedback);
    output.value = ''; copy.disabled = download.disabled = true; copy.textContent = 'Copy Python Code';
    error.hidden = true; error.textContent = ''; input.removeAttribute('aria-invalid');
  }
  function run() {
    invalidate();
    const framework = doc.querySelector('input[name="pydantic-framework"]:checked').value;
    defaults.disabled = framework !== 'pydantic';
    if (!input.value.trim()) { status.textContent = 'Ready. Your JSON stays in this browser.'; return; }
    try {
      output.value = generate(input.value, { framework, optional: doc.getElementById('pydantic-optional').checked, fieldDefaults: defaults.checked, snakeCase: doc.getElementById('pydantic-snake').checked });
      copy.disabled = download.disabled = false; status.textContent = 'Python code generated locally. Review inferred types before use.';
    } catch (cause) {
      input.setAttribute('aria-invalid', 'true'); error.textContent = cause.message || 'Unable to generate Python code.'; error.hidden = false;
      status.textContent = 'Check the input error below the editor.';
    }
  }
  function schedule() { invalidate(); status.textContent = 'Checking JSON…'; timer = win.setTimeout(run, 150); }
  ['input', 'paste', 'keyup'].forEach(event => input.addEventListener(event, schedule));
  input.addEventListener('change', run);
  doc.querySelectorAll('input[name="pydantic-framework"], #pydantic-optional, #pydantic-defaults, #pydantic-snake').forEach(control => control.addEventListener('change', run));
  doc.getElementById('pydantic-clear').addEventListener('click', () => { input.value = ''; run(); input.focus(); });
  copy.addEventListener('click', async () => {
    if (!output.value) return;
    const current = revision;
    try {
      await win.navigator.clipboard.writeText(output.value);
      if (current !== revision) return;
      copy.textContent = 'Copied!'; status.textContent = 'Python code copied.';
      feedback = win.setTimeout(() => { copy.textContent = 'Copy Python Code'; }, 1800);
    } catch (_) {
      if (current !== revision) return;
      output.focus(); output.select(); status.textContent = 'Clipboard unavailable. Output selected; press Ctrl+C or Command+C.';
    }
  });
  download.addEventListener('click', () => {
    if (!output.value) return;
    const url = win.URL.createObjectURL(new win.Blob([output.value], { type: 'text/x-python;charset=utf-8' }));
    const link = doc.createElement('a'); link.href = url; link.download = 'models.py';
    doc.body.append(link); link.click(); link.remove(); win.setTimeout(() => win.URL.revokeObjectURL(url), 1000);
    status.textContent = 'Python file downloaded.';
  });
  try {
    const saved = win.sessionStorage.getItem(HANDOFF_KEY);
    if (saved !== null) { input.value = saved; win.sessionStorage.removeItem(HANDOFF_KEY); }
  } catch (_) { /* Manual input remains available when storage is blocked. */ }
  run();
}
if (typeof document !== 'undefined') init();
