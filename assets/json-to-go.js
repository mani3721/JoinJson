/* Dependency-free JSON sample inference. No input is transmitted. */
export const HANDOFF_KEY = 'joinjson:go-input';
const initialisms = new Set(['API', 'ASCII', 'CPU', 'CSS', 'DNS', 'EOF', 'GUID', 'HTML', 'HTTP', 'HTTPS', 'ID', 'IP', 'JSON', 'QPS', 'RAM', 'RPC', 'SLA', 'SMTP', 'SQL', 'SSH', 'TCP', 'TLS', 'TTL', 'UDP', 'UI', 'UID', 'UUID', 'URI', 'URL', 'UTF8', 'VM', 'XML', 'XSRF', 'XSS']);
export function goName(value, fallback = 'Field') {
  const words = String(value).replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2').replace(/([a-z0-9])([A-Z])/g, '$1 $2').split(/[^a-zA-Z0-9]+/).filter(Boolean);
  let name = words.map(word => initialisms.has(word.toUpperCase()) ? word.toUpperCase() : word[0].toUpperCase() + word.slice(1)).join('') || fallback;
  if (/^[0-9]/.test(name)) name = 'Field' + name;
  return name;
}
const any = () => ({ kind: 'interface{}' });
function merge(a, b) {
  if (!a) return b;
  if (!b) return a;
  if (a.kind === 'null') return b.kind === 'null' ? a : { ...b, nullable: true };
  if (b.kind === 'null') return { ...a, nullable: true };
  const nullable = a.nullable || b.nullable;
  if (a.kind !== b.kind) {
    if (['int64', 'float64'].includes(a.kind) && ['int64', 'float64'].includes(b.kind)) return { kind: 'float64', nullable };
    return any();
  }
  if (a.kind === 'object') {
    const fields = new Map();
    for (const key of new Set([...a.fields.keys(), ...b.fields.keys()])) {
      const left = a.fields.get(key), right = b.fields.get(key);
      fields.set(key, { schema: merge(left?.schema, right?.schema), optional: !left || !right || left.optional || right.optional });
    }
    return { kind: 'object', fields, nullable };
  }
  if (a.kind === 'array') return { kind: 'array', item: merge(a.item, b.item), nullable };
  return { ...a, nullable };
}
function infer(value, depth = 0) {
  if (depth > 100) throw new Error('JSON nesting exceeds the supported depth of 100 levels.');
  if (value === null) return { kind: 'null' };
  if (Array.isArray(value)) return { kind: 'array', item: value.reduce((schema, item) => merge(schema, infer(item, depth + 1)), undefined) };
  if (typeof value === 'object') return { kind: 'object', fields: new Map(Object.entries(value).map(([key, child]) => [key, { schema: infer(child, depth + 1), optional: false }])) };
  if (typeof value === 'number') {
    if (!Number.isFinite(value) || (Number.isInteger(value) && !Number.isSafeInteger(value))) throw new Error('A number is outside JavaScript’s safe range. Encode exact large integers as strings before generating structs.');
    return { kind: Number.isInteger(value) ? 'int64' : 'float64' };
  }
  return { kind: typeof value === 'boolean' ? 'bool' : 'string' };
}
function allocate(base, used) {
  let name = base, suffix = 2;
  while (used.has(name)) name = base + suffix++;
  used.add(name);
  return name;
}
export function generate(source, { rootName = 'AutoGenerated', includeTags = true, omitEmpty = false } = {}) {
  if (!source.trim()) return '';
  const value = JSON.parse(source);
  if (!value || typeof value !== 'object') throw new Error('Paste a JSON object or array, not a primitive value.');
  const root = infer(value), rootType = goName(rootName.trim() || 'AutoGenerated', 'AutoGenerated');
  const used = new Set([rootType]), definitions = [];
  function render(schema, hint, optional = false) {
    if (!schema || schema.kind === 'null' || schema.kind === 'interface{}') return 'interface{}';
    let type;
    if (schema.kind === 'object') {
      type = allocate(hint, used);
      object(schema, type);
    } else if (schema.kind === 'array') type = '[]' + render(schema.item, hint + 'Item');
    else type = schema.kind;
    return (schema.nullable || optional) && !type.startsWith('[]') ? '*' + type : type;
  }
  function object(schema, name) {
    const index = definitions.length;
    definitions.push('');
    const fieldsUsed = new Set();
    const fields = [...schema.fields].map(([key, field]) => {
      const fieldName = allocate(goName(key), fieldsUsed);
      const type = render(field.schema, name + fieldName, field.optional);
      let tag = '';
      if (includeTags) {
        // encoding/json cannot express these names faithfully in a struct tag.
        if (!key || key === '-' || /[,"\\\x00-\x1f\x7f]/.test(key) || [...key].some(char => !/[\p{L}\p{N}\s!#$%&()*+\-./:;<=>?@\[\]^_{|}~ ]/u.test(char))) {
          throw new Error(`Key ${JSON.stringify(key)} cannot be represented faithfully by a Go json struct tag. Rename the key or disable json tags.`);
        }
        const body = 'json:' + JSON.stringify(key + (omitEmpty ? ',omitempty' : ''));
        tag = ' ' + (body.includes('`') ? JSON.stringify(body) : '`' + body + '`');
      }
      return '\t' + fieldName + ' ' + type + tag;
    });
    definitions[index] = 'type ' + name + ' struct {' + (fields.length ? '\n' + fields.join('\n') + '\n' : '') + '}';
  }
  if (root.kind === 'object') object(root, rootType);
  else {
    definitions.push('');
    const type = render(root, rootType);
    definitions[0] = 'type ' + rootType + ' ' + type;
  }
  return '// Generated from a JSON sample. Review types against your API schema.\n// Null-only, empty-array and mixed-type values use interface{}.\n\npackage main\n\n' + definitions.join('\n\n') + '\n';
}
export function init(doc = document) {
  const input = doc.getElementById('go-json-input');
  if (!input) return;
  const win = doc.defaultView;
  const output = doc.getElementById('go-output'), root = doc.getElementById('root-struct-name');
  const tags = doc.getElementById('go-tags'), omit = doc.getElementById('go-omitempty');
  const error = doc.getElementById('go-error'), status = doc.getElementById('go-status');
  const copy = doc.getElementById('go-copy'), download = doc.getElementById('go-download');
  let timer, feedback, revision = 0;
  function invalidate() {
    revision++;
    win.clearTimeout(timer); win.clearTimeout(feedback);
    output.value = ''; copy.disabled = download.disabled = true;
    copy.textContent = 'Copy Go Code'; error.hidden = true; error.textContent = '';
    input.removeAttribute('aria-invalid');
  }
  function run() {
    invalidate(); omit.disabled = !tags.checked;
    if (!input.value.trim()) { status.textContent = 'Ready. Your JSON stays in this browser.'; return; }
    try {
      output.value = generate(input.value, { rootName: root.value, includeTags: tags.checked, omitEmpty: omit.checked });
      copy.disabled = download.disabled = false;
      status.textContent = 'Go structs generated locally. Review inferred types before use.';
    } catch (cause) {
      input.setAttribute('aria-invalid', 'true');
      error.textContent = cause.message || 'Unable to generate Go structs.'; error.hidden = false;
      status.textContent = 'Check the input error below the editor.';
    }
  }
  function schedule() { invalidate(); status.textContent = 'Checking JSON…'; timer = win.setTimeout(run, 150); }
  input.addEventListener('input', schedule);
  input.addEventListener('keyup', event => { if (!['Tab', 'Shift', 'Control', 'Alt', 'Meta'].includes(event.key)) schedule(); });
  input.addEventListener('paste', schedule);
  input.addEventListener('change', run);
  root.addEventListener('input', schedule);
  [root, tags, omit].forEach(control => control.addEventListener('change', run));
  doc.getElementById('go-clear').addEventListener('click', () => { input.value = ''; run(); input.focus(); });
  copy.addEventListener('click', async () => {
    if (!output.value) return;
    const current = revision;
    try {
      await win.navigator.clipboard.writeText(output.value);
      if (current !== revision) return;
      copy.textContent = 'Copied!'; status.textContent = 'Go code copied.';
      feedback = win.setTimeout(() => { copy.textContent = 'Copy Go Code'; }, 1800);
    } catch (_) {
      if (current !== revision) return;
      output.focus(); output.select(); status.textContent = 'Clipboard unavailable. Output selected; press Ctrl+C or Command+C.';
    }
  });
  download.addEventListener('click', () => {
    if (!output.value) return;
    const url = win.URL.createObjectURL(new win.Blob([output.value], { type: 'text/plain;charset=utf-8' }));
    const link = doc.createElement('a'); link.href = url;
    link.download = goName(root.value.trim() || 'AutoGenerated').toLowerCase() + '.go';
    doc.body.append(link); link.click(); link.remove();
    win.setTimeout(() => win.URL.revokeObjectURL(url), 1000);
    status.textContent = 'Go file downloaded.';
  });
  try {
    const saved = win.sessionStorage.getItem(HANDOFF_KEY);
    if (saved !== null) { input.value = saved; win.sessionStorage.removeItem(HANDOFF_KEY); }
  } catch (_) { /* Manual input still works when storage is blocked. */ }
  run();
}
if (typeof document !== 'undefined') init();
